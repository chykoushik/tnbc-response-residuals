stage03_run("07_score_pathways", {
  verify_stage02()
  sets <- read_frozen_panel()
  authority <- blinded_identity()
  expression <- read_pathway_expression(authority$identity)
  pathway_coverage(sets, rownames(expression))
  scores <- score_pathways(expression, sets, authority$identity)
  qc <- score_qc(scores)
  write_tsv(qc, path("results/stage03_pathways/pathway_score_qc.tsv"))
  if (any(!qc$passed)) stage03_stop("Score QC failed")
  connection <- gzfile(path(primary_files[2]), "wt")
  tryCatch(write_tsv(scores, connection), finally = close(connection))
  paired <- pair_pathway_scores(scores, authority$pairs)
  write_tsv(paired, path(primary_files[3]))
  inputs <- link_pathway_composition(paired, authority$pairs)
  write_tsv(inputs, path(primary_files[4]))
  leakage_qc()
  pathway_figures(scores)
})
cat("Scores validated\n")
